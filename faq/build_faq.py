def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--store", default="pgvector", choices=["sqlite", "pgvector"])
    args = ap.parse_args()

    cfg = yaml.safe_load(open(os.path.join(ROOT, args.config), encoding="utf-8"))
    tenant = cfg["tenant_id"]
    pipe = build_pipeline(cfg, args.store, "openai", "openai")

    cards = []
    for cid, cat, q, ans in GENERAL_FAQ:
        # источник — ретривалом по ВСЕМ вузам (None); прикрепляем, если нашёлся релевантный документ
        qv = pipe.embedder.embed_query(q)
        chunks = pipe.store.search(qv, q, tenant_id=None, top_k=1, categories=None)
        source = None
        if chunks:
            c = chunks[0]
            source = {"label": _label(c), "url": c.get("source_url"),
                      "page": c.get("page_number"), "section": c.get("section_title"),
                      "university": c.get("tenant_id")}
        cards.append({"id": cid, "category": cat, "category_label": CAT_LABEL.get(cat, cat),
                      "question": q, "answer": ans, "source": source})
        print(f"[ok] {cid:4} [{cat}] источник: {source['label'] if source else '—'}")

    out = os.path.join(ROOT, "data", tenant, "faq.json")
    json.dump({"tenant": tenant, "count": len(cards), "cards": cards},
              open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"\nГотово: {len(cards)} общих карточек FAQ → {out}")


if __name__ == "__main__":
    main()

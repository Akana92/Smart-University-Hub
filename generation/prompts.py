# ─────────── Мультиязычность советника (TASK-030): ответ на языке сообщения ───────────
# Продукт отвечает «на языке сообщения». Контекст в базе — на русском; модель переводит
# факты на язык ответа. Термины (ЕНТ/ГОП/GPA/IELTS) не переводим. Строгий режим (ТЗ) не трогаем.
